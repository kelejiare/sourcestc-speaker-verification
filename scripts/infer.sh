#!/usr/bin/env bash
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ARCHIVE="${MODEL_PACKAGE:-$PROJECT_DIR/weights/sourcestc-weights.tar.gz}"
UNPACK="$PROJECT_DIR/weights/prepared"
RUNTIME="$PROJECT_DIR/inference"
INPUT="${XFDATA_ROOT:-$PROJECT_DIR/data/sourcestc-test}"
OUTPUT="${PREDICTION_RESULT_DIR:-$PROJECT_DIR/outputs}"

MODEL="$(python3 "$PROJECT_DIR/scripts/prepare_weights.py" "$ARCHIVE" --output "$UNPACK")"
export GAME823_INPUT_DIR="$INPUT"
export OUTPUT_DIR="$OUTPUT"
export GAME823_PT_MODEL_PATH="$MODEL/model_pt.pt"
export GAME823_CAMPPLUS_MODEL_PATH="$MODEL/campplus_cn_en_common.pt"
export GAME823_REDIM_LM_MODEL_PATH="$MODEL/redimnet2-b6-vb2-vox2-cnc2-lm.pt"
export GAME823_REDIM_PTN_MODEL_PATH="$MODEL/redimnet2-b6-vb2-vox2-cnc2-ptn.pt"
export GAME823_JOINT_ADAPTER_PATH="$MODEL/joint_kd_adapter.npz"
export GAME823_MOBILE_ADAPTER_PATH="$MODEL/mobile_kd_adapter.npz"
export GAME823_SHORT_METRIC_ADAPTER_PATH="$MODEL/short_duration_metric_adapter.npz"
export GAME823_SHORT_PT_ADAPTER_PATH="$MODEL/short_duration_pt_adapter.npz"
export GAME823_REDIMNET2PLUS_MODEL_PATH="$MODEL/redimnet2plus-b6-lmft-robust.pt"
export GAME823_W2VBERT2_MODEL_PATH="$MODEL/w2vbert2-multidomain-speaker-fp16.pt"
export GAME823_LORA_PATCH_PATH="$MODEL/lora_duration_patch.pt"
export GAME823_W2VBERT2_CONFIG_DIR="$RUNTIME/w2vbert2_config"
mkdir -p "$OUTPUT"
exec python3 "$RUNTIME/run.py"
